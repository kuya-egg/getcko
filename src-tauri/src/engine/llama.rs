    #[test]
    #[ignore = "needs model files"]
    fn gemma_transcribes_optional_grade_fixture() {
        let wav_path = std::path::Path::new("/tmp/q_en.wav");
        if !wav_path.is_file() {
            return;
        }
        let bytes = std::fs::read(wav_path).expect("WAV fixture reads");
        assert!(bytes.len() >= 44);
        assert_eq!(&bytes[..4], b"RIFF");
        assert_eq!(&bytes[8..12], b"WAVE");
        // `say` writes extra chunks before `fmt `, so locate it instead of assuming offset 12.
        let fmt = bytes
            .windows(4)
            .position(|window| window == b"fmt ")
            .expect("WAV fmt chunk exists")
            + 8;
        let u16_at = |at: usize| u16::from_le_bytes([bytes[at], bytes[at + 1]]);
        assert_eq!(u16_at(fmt), 1, "PCM");
        assert_eq!(u16_at(fmt + 2), 1, "mono");
        assert_eq!(
            u32::from_le_bytes([
                bytes[fmt + 4],
                bytes[fmt + 5],
                bytes[fmt + 6],
                bytes[fmt + 7]
            ]),
            16_000
        );
        assert_eq!(u16_at(fmt + 14), 16, "16-bit");
        let data_offset = bytes
            .windows(4)
            .position(|window| window == b"data")
            .map(|position| position + 8)
            .expect("WAV data chunk exists");
        let pcm = bytes[data_offset..]
            .as_chunks::<2>()
            .0
            .iter()
            .map(|sample| f32::from(i16::from_le_bytes([sample[0], sample[1]])) / 32_768.0)
            .collect::<Vec<_>>();
        let rt = Runtime::init().expect("runtime initializes");
        let model = LlamaChat::load(
            &rt,
            &model_path("gemma-4-E2B-it-Q4_0.gguf"),
            &model_path("mmproj-gemma-4-E2B-it-Q8_0.gguf"),
        )
        .expect("chat and projector load");
        assert!(model.supports_audio());
        let transcript = model
            .transcribe(&pcm, Language::English)
            .expect("speech transcribes");
        assert!(transcript.to_lowercase().contains("grade"));
    }
